import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
const browser=await chromium.launch({args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
await context.route(/^https?:/,r=>r.abort());
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
const file='file:///home/user/Play-Digital-Preview.html';
await page.goto(file,{waitUntil:'domcontentloaded'});
await expect(page.locator('h1')).toHaveText('Human-led.AI-amplified.');
await page.evaluate(()=>document.fonts.ready);
await expect(page.locator('.hero-poster')).toHaveJSProperty('naturalWidth',1280);
await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Work',exact:true}).click();
await expect(page.locator('.work-card')).toHaveCount(5);
const images=await page.locator('.work-image img').evaluateAll(images=>images.every(i=>i.complete&&i.naturalWidth>0));expect(images).toBe(true);
await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Client',exact:true}).click();
await expect(page.locator('.client-card')).toHaveCount(32);
console.log('FILE PREVIEW: all-inline rendering, offline images, routes and 32 clients passed.');
const html=await fs.readFile('/home/user/Play-Digital-Preview.html','utf8');
const iframePage=await context.newPage();iframePage.on('pageerror',e=>errors.push(e.message));
await iframePage.setContent('<iframe id="preview" sandbox="allow-scripts" style="width:100%;height:950px;border:0"></iframe>');
const safe=html.replace('<head>','<head><meta http-equiv="Content-Security-Policy" content="default-src \'none\'; script-src \'unsafe-inline\'; style-src \'unsafe-inline\'; img-src data:; font-src data:; frame-src \'none\'; connect-src \'none\';">');
await iframePage.locator('#preview').evaluate((frame,content)=>frame.srcdoc=content,safe);
const f=iframePage.frameLocator('#preview');
await expect(f.locator('h1')).toHaveText('Human-led.AI-amplified.');
await f.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Services',exact:true}).click();
await expect(f.locator('h1')).toHaveText('One partner.Every possibility.');
await f.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Work',exact:true}).click();
await expect(f.locator('.work-card')).toHaveCount(5);
console.log('SANDBOXED FILE VIEWER: scripts-only iframe, blocked network, internal navigation passed.');
console.log('PAGE_ERRORS:',errors);expect(errors).toEqual([]);
await browser.close();
